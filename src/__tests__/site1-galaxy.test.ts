describe('SITE1-2 — sphere geometry (app rules)', () => {
  const s = buildSphere(374, 4242, TRACKS);
  it('places 7 planets on the orbit, the title on repeat ringed, sizes by plays', () => {
    expect(s.planets).toHaveLength(7);
    expect(s.planets[0].ringed).toBe(true);
    expect(s.planets.filter((p) => p.ringed)).toHaveLength(1);
    expect(s.planets[0].pr).toBeGreaterThan(s.planets[6].pr);
    expect(s.orbitR).toBeCloseTo(374 / 2 * 0.66);
    expect(s.planets[0].moodColor).toBe('#FF3CAC'); // 8 PM = evening (deriveMoodColorFromHour)
    expect(s.planets[2].moodColor).toBe('#7B2FFF'); // 10 PM = night
  });
  it('resolves a tap on each planet where it is drawn, and nothing in the void', () => {
    for (const t of [0, 1.3, 4]) {
      s.planets.forEach((p, i) => {
        const a = planetAt(s, p, t, 0.4, -0.2);
        expect(planetUnder(s, a.x, a.y, t, 0.4, -0.2)).toBe(i);
      });
    }
    expect(planetUnder(s, -500, -500, 0)).toBeNull();
  });
  it('uses the app seed (account id never sent to the browser)', () => {
    expect(seedFromUserId('abc')).toBe((97 + 98 + 99) % 9973);
  });
});

describe('SITE1-2 — founder data', () => {
  it('reads only the founder account, cleaned titles, no private listen', () => {
    const src = read('src/lib/founderGalaxy.ts');
    expect(FOUNDER_USERNAME).toBe('bertrand');
    expect(src).toContain(".eq('username', FOUNDER_USERNAME)");
    expect(src).toContain('u.deleted_at || u.is_banned === true');
    expect(src).toContain(".eq('is_private', false)");
    expect(src).toContain(".not('track_title_normalized', 'is', null).not('artist_name_normalized', 'is', null)");
    expect(src).not.toMatch(/\bid:\s*u\.id\b/);
  });
  it('can be switched off', () => {
    expect(founderGalaxyEnabled({})).toBe(true);
    expect(founderGalaxyEnabled({ FOUNDER_GALAXY: 'off' })).toBe(false);
    expect(founderGalaxyEnabled({ FOUNDER_GALAXY: ' OFF ' })).toBe(false);
  });
  it('maps at most 7 defining tracks', () => {
    const rows = Array.from({ length: 9 }, (_, i) => ({ track_id: `t${i}`, title: `T${i}`, artist: 'A', play_count: '3', peak_local_hour: i === 0 ? null : 21 }));
    const t = toFounderTracks(rows);
    expect(t).toHaveLength(7);
    expect(t[0]).toEqual({ trackId: 't0', title: 'T0', artist: 'A', playCount: 3, peakLocalHour: null });
    expect(toFounderTracks(null)).toEqual([]);
  });
});

